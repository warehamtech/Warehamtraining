/**
 * @param name  a key of PATHS
 * @param size  pixel size; 16 suits inline text, 20 a button, 24 a heading
 */
export function icon(name, size = 16, attrs = {}) {
  const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("width", size);
  svg.setAttribute("height", size);
  svg.setAttribute("fill", "none");
  svg.setAttribute("stroke", "currentColor");
  svg.setAttribute("stroke-width", attrs.strokeWidth ?? 2);
  svg.setAttribute("stroke-linecap", "round");
  svg.setAttribute("stroke-linejoin", "round");
  svg.setAttribute("aria-hidden", "true");
  if (attrs.class) svg.setAttribute("class", attrs.class);
  svg.innerHTML = PATHS[name] ?? "";
  return svg;
}

