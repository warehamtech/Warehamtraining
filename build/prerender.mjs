/**
 * Write the public pages' content into their HTML.
 *
 *   node build/prerender.mjs           regenerate
 *   node build/prerender.mjs --check   fail if anything committed is out of date
 *
 * WHY
 *
 * The signed-in half of the portal is a private application: it can render
 * itself in the browser and nothing is lost. The public half cannot. Left to
 * client rendering, /programs ships the words "Loading the catalogue…" and
 * every programme shares one URL with one hardcoded <title>, so a crawler sees
 * a single untitled page and a link pasted into WhatsApp or LinkedIn unfurls
 * as "Programme — WHA Learning Portal". For a business whose customers search
 * for "ISO 9001 training" that is the wrong set of pages to leave empty.
 *
 * So this fills them in: the landing page, the catalogue, and one real file per
 * published programme.
 *
 * HOW IT AVOIDS BECOMING A SECOND COPY OF THE SITE
 *
 * It does not own any markup. It imports the very same render functions the
 * browser runs — home.js's catalogueNodes(), program.js's programNodes(),
 * shell.js's publicHeaderNodes() — and runs them against a linkedom document.
 * A template that existed only here would drift the first time someone edited
 * the page module and not this file; there is no such template.
 *
 * For the same reason it does not re-implement the queries: it evaluates the
 * vendored Supabase build and calls catalog.js, so the data shape can only be
 * whatever the site itself asks for.
 *
 * WHAT IT IS NOT
 *
 * Not a build step in the sense the README rules out. It edits committed files
 * in place; site/ stays the finished website that Netlify serves as-is and that
 * still opens from disk. Netlify re-runs it on deploy only to pick up catalogue
 * changes, and is configured so that a failure here cannot fail a deploy — the
 * committed HTML simply ships as it stands. The pages also still fetch and
 * re-render in the browser, so a stale generated copy is a stale first paint
 * and never stale data.
 */
import { readFileSync, writeFileSync, unlinkSync, readdirSync } from "node:fs";
import { join, resolve } from "node:path";
import { runInThisContext } from "node:vm";
import { parseHTML } from "linkedom";

const ROOT = resolve(import.meta.dirname, "..");
const SITE = join(ROOT, "site");
const CHECK = process.argv.includes("--check");

/** Matches WHA_SITE_URL in supabase/functions/_shared/wha.ts. Canonical URLs
 *  and og:url must be absolute, and `location.origin` does not exist here. */
const SITE_URL = (process.env.WHA_SITE_URL ?? "https://wha.co.za").replace(/\/+$/, "");

/** Stamped into every file this generates, so it can find them again to clean
 *  up after a programme is unpublished. Nothing hand-written carries it. */
const GENERATED_MARK = "<!-- This file is generated by build/prerender.mjs. Do not edit by hand. -->";

/* --- A browser, more or less ---------------------------------------------- */

/**
 * The site's modules assume a browser. Give them one before importing any of
 * them: linkedom for the DOM, memory stubs for the storage the Supabase client
 * touches on construction, and a location that env.js can read an origin from.
 */
function installBrowserGlobals() {
  const { document, window, Node, CustomEvent } = parseHTML(
    "<!doctype html><html><head></head><body></body></html>",
  );

  const memoryStorage = () => {
    const map = new Map();
    return {
      getItem: (k) => (map.has(k) ? map.get(k) : null),
      setItem: (k, v) => map.set(k, String(v)),
      removeItem: (k) => map.delete(k),
      clear: () => map.clear(),
      key: (i) => [...map.keys()][i] ?? null,
      get length() { return map.size; },
    };
  };

  teachLinkedomAboutSvg(document);

  globalThis.document = document;
  globalThis.window = window;
  // dom.js's append() branches on `child instanceof Node`, so this has to be
  // linkedom's Node and not some other implementation's.
  globalThis.Node = Node;
  globalThis.CustomEvent = CustomEvent;
  globalThis.location = new URL(SITE_URL + "/");
  globalThis.localStorage = memoryStorage();
  globalThis.sessionStorage = memoryStorage();
}

const SVG_NS = "http://www.w3.org/2000/svg";

/**
 * Make `svg.innerHTML = "<path d='…'/>"` mean what it means in a browser.
 *
 * icons.js stores each glyph as SVG source copied from Lucide, which uses XML
 * self-closing tags, and assigns it with innerHTML onto an element created in
 * the SVG namespace. A browser parses that as foreign content, where `/>`
 * genuinely closes the tag, and gets sibling <path> elements. linkedom parses
 * it with HTML rules, where `/>` on an unknown element is ignored — so each
 * path swallows the next and a three-stroke icon comes out as one path nested
 * three deep. Every icon on every generated page would be silently wrong.
 *
 * The normalisation is applied here rather than by rewriting icons.js, because
 * icons.js is not the thing that is broken: it is correct everywhere it
 * actually runs. Scoped to elements in the SVG namespace, so nothing else —
 * dom.js's rawHtml(), for instance — is affected.
 */
function teachLinkedomAboutSvg(document) {
  const sample = document.createElementNS(SVG_NS, "svg");
  let owner = Object.getPrototypeOf(sample);
  while (owner && !Object.getOwnPropertyDescriptor(owner, "innerHTML")) {
    owner = Object.getPrototypeOf(owner);
  }
  if (!owner) throw new Error("linkedom: could not find the innerHTML accessor to patch");
  const innerHTML = Object.getOwnPropertyDescriptor(owner, "innerHTML");

  // <path d="…"/>  ->  <path d="…"></path>, leaving quoted attribute values
  // (which may themselves contain "/" or ">") alone.
  const expand = (source) =>
    String(source).replace(
      /<([a-zA-Z][\w-]*)((?:[^>"']|"[^"]*"|'[^']*')*?)\s*\/>/g,
      "<$1$2></$1>",
    );

  const create = document.createElementNS.bind(document);
  document.createElementNS = (ns, name) => {
    const node = create(ns, name);
    if (ns === SVG_NS) {
      Object.defineProperty(node, "innerHTML", {
        configurable: true,
        get: () => innerHTML.get.call(node),
        set: (value) => innerHTML.set.call(node, expand(value)),
      });
    }
    return node;
  };
}

/**
 * The real Supabase client, from the copy already vendored into the site.
 *
 * Installing it rather than adding @supabase/supabase-js as a dependency keeps
 * one library at one version: whatever the browser runs is what generates these
 * pages, and an upgrade to assets/vendor/supabase.js cannot leave this out of
 * step. The file is a self-contained UMD bundle whose top-level `var supabase`
 * becomes the global that assets/js/supabase.js looks for.
 */
function installSupabase() {
  runInThisContext(readFileSync(join(SITE, "assets/vendor/supabase.js"), "utf8"));
  if (!globalThis.supabase?.createClient) {
    throw new Error("assets/vendor/supabase.js did not define createClient.");
  }
}

/* --- HTML splicing --------------------------------------------------------
 *
 * String surgery rather than parse-and-reserialise. Round-tripping these files
 * through a DOM is very nearly lossless, but "very nearly" means it rewrites
 * the doctype's case and turns `&amp;` in the existing meta description back
 * into a bare `&` — churning hand-authored markup this script has no business
 * touching. Replacing a named region leaves everything else byte-identical.
 */

/**
 * The title format dom.js's setTitle() produces. It has to be this and not the
 * em-dash the hand-written pages use, because on a generated programme page
 * both run: the generator writes the title a crawler and an unfurler read, and
 * then program.js calls setTitle() over the top of it in the browser. Any other
 * format here and the tab title visibly changes a moment after the page loads.
 */
const pageTitle = (title) => `${title} · WHA Learning Portal`;

const escapeAttr = (value) =>
  String(value ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll('"', "&quot;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;");

/** Replace the contents of the element carrying `id`, keeping its own tag. */
function replaceInner(html, id, inner) {
  const idAt = html.indexOf(`id="${id}"`);
  if (idAt === -1) throw new Error(`no element with id="${id}"`);

  const open = html.lastIndexOf("<", idAt);
  const tag = html.slice(open + 1).match(/^[a-zA-Z][\w-]*/)?.[0];
  if (!tag) throw new Error(`could not read the tag name opening id="${id}"`);

  const openEnd = html.indexOf(">", idAt) + 1;
  const scan = new RegExp(`<${tag}\\b|</${tag}>`, "gi");
  scan.lastIndex = openEnd;

  let depth = 1;
  let match;
  while ((match = scan.exec(html))) {
    depth += match[0][1] === "/" ? -1 : 1;
    if (depth === 0) return html.slice(0, openEnd) + inner + html.slice(match.index);
  }
  throw new Error(`unbalanced <${tag}> around id="${id}"`);
}

/** Set (or add) one attribute on the element carrying `id`. */
function setAttribute(html, id, name, value) {
  const idAt = html.indexOf(`id="${id}"`);
  if (idAt === -1) throw new Error(`no element with id="${id}"`);
  const openEnd = html.indexOf(">", idAt);
  const tag = html.slice(html.lastIndexOf("<", idAt), openEnd + 1);

  const next = new RegExp(`\\s${name}="[^"]*"`).test(tag)
    ? tag.replace(new RegExp(`\\s${name}="[^"]*"`), ` ${name}="${escapeAttr(value)}"`)
    : tag.replace(/>$/, ` ${name}="${escapeAttr(value)}">`);

  return html.slice(0, html.lastIndexOf("<", idAt)) + next + html.slice(openEnd + 1);
}

/** Replace, or insert, a comment-delimited region. */
function replaceRegion(html, startMark, endMark, body, insertBefore) {
  const region = `${startMark}\n${body}\n${endMark}`;
  const i = html.indexOf(startMark);
  if (i !== -1) {
    const j = html.indexOf(endMark) + endMark.length;
    return html.slice(0, i) + region + html.slice(j);
  }
  if (!html.includes(insertBefore)) throw new Error(`no anchor to insert before: ${insertBefore}`);
  return html.replace(insertBefore, `${region}\n${insertBefore}`);
}

const META_START = "<!-- social preview: generated by build/prerender.mjs -->";
const META_END = "<!-- end social preview -->";

/**
 * Canonical URL and the Open Graph tags that decide what a link to this page
 * looks like when someone pastes it into WhatsApp, LinkedIn or an email client.
 * Unfurlers do not run JavaScript, which is why setTitle() in the page module
 * was never enough on its own.
 */
function socialBlock({ path, title, description }) {
  const url = `${SITE_URL}${path}`;
  const image = `${SITE_URL}/assets/brand/wha-logo.png`;
  return [
    `<link rel="canonical" href="${escapeAttr(url)}">`,
    `<meta property="og:type" content="website">`,
    `<meta property="og:site_name" content="WHA Learning Portal">`,
    `<meta property="og:title" content="${escapeAttr(title)}">`,
    `<meta property="og:description" content="${escapeAttr(description)}">`,
    `<meta property="og:url" content="${escapeAttr(url)}">`,
    `<meta property="og:image" content="${escapeAttr(image)}">`,
    `<meta name="twitter:card" content="summary">`,
    `<meta name="twitter:title" content="${escapeAttr(title)}">`,
    `<meta name="twitter:description" content="${escapeAttr(description)}">`,
  ].join("\n");
}

/* --- Page generation ------------------------------------------------------ */

const read = (rel) => readFileSync(join(SITE, rel), "utf8");

/** Render a list of nodes to HTML. */
const html = (nodes) =>
  (Array.isArray(nodes) ? nodes : [nodes])
    .filter(Boolean)
    .map((n) => n.outerHTML ?? n.textContent ?? "")
    .join("");

async function main() {
  installBrowserGlobals();
  installSupabase();

  // Imported only after the globals exist — assets/js/supabase.js throws at
  // module scope if the library is not there, and shell.js registers a window
  // listener at module scope.
  const shell = await import(new URL("../site/assets/js/shell.js", import.meta.url));
  const catalog = await import(new URL("../site/assets/js/catalog.js", import.meta.url));
  const homePage = await import(new URL("../site/assets/js/pages/home.js", import.meta.url));
  const programsPage = await import(new URL("../site/assets/js/pages/programs.js", import.meta.url));
  const programPage = await import(new URL("../site/assets/js/pages/program.js", import.meta.url));

  // Anonymous, exactly as the generated pages are read. Row level security
  // therefore hands over published programmes only, which is precisely the set
  // that should get a file — a draft stays reachable at
  // /programs/program.html?slug= for the WHA staff who can see it.
  const programs = await catalog.listPrograms();

  // The chrome is generated signed-out. publicChrome() still runs in the
  // browser and redraws it, which is a no-op for an anonymous reader and an
  // upgrade to the app header for a signed-in one.
  const headerHtml = html(shell.publicHeaderNodes(null));
  const footerHtml = html(shell.footerNodes(null));

  const withChrome = (source) => {
    let out = replaceInner(source, "site-header", headerHtml);
    out = setAttribute(out, "site-header", "class", shell.PUBLIC_HEADER_CLASS);
    out = replaceInner(out, "site-footer", footerHtml);
    return setAttribute(out, "site-footer", "class", shell.FOOTER_CLASS);
  };

  /** rel path -> contents. Written (or compared) all at once at the end. */
  const output = new Map();

  /* Landing page. */
  {
    let out = withChrome(read("index.html"));
    out = replaceInner(out, "trust", html(homePage.trustNodes()));
    out = replaceInner(out, "steps", html(homePage.stepsNodes()));
    out = replaceInner(out, "catalogue",
      html(homePage.catalogueNodes(programs.slice(0, homePage.PREVIEW_LIMIT))));
    out = replaceRegion(out, META_START, META_END, socialBlock({
      path: "/",
      title: "WHA Learning Portal — Compliance training from Wareham & Associates",
      description:
        "World-class online training in international standards — ISO 9001, FSSC 22000, BRCGS and more. Led by subject matter experts and trusted by manufacturers across Africa.",
    }), '<link rel="icon"');
    output.set("index.html", out);
  }

  /* Catalogue. */
  {
    let out = withChrome(read("programs/index.html"));
    out = replaceInner(out, "catalogue", html(programsPage.catalogueNodes(programs)));
    out = replaceRegion(out, META_START, META_END, socialBlock({
      path: "/programs/index.html",
      title: "Training catalogue — WHA Learning Portal",
      description:
        "Online training programmes in ISO 9001, FSSC 22000, BRCGS and other international standards, from Wareham & Associates.",
    }), '<link rel="icon"');
    output.set("programs/index.html", out);
  }

  /* One file per published programme. */
  const template = read("programs/program.html");
  for (const card of programs) {
    const program = await catalog.getProgramBySlug(card.slug);
    if (!program) continue;

    const path = `/programs/${program.slug}.html`;

    // `summary` is optional in the admin editor, and an empty description is
    // worse than a generic one: search results and link previews fall back to
    // scraping whatever text they find first, which here is the navigation.
    const description = program.summary?.trim()
      || [program.title, program.standard].filter(Boolean).join(" · ")
        + " — online compliance training from Wareham & Associates.";

    let out = withChrome(template);
    out = replaceInner(out, "app", html(programPage.programNodes(program)));
    out = out.replace(
      /<title>[^<]*<\/title>/,
      `<title>${escapeAttr(pageTitle(program.title))}</title>`,
    );
    out = out.replace(
      /<meta name="description" content="[^"]*">/,
      `<meta name="description" content="${escapeAttr(description)}">`,
    );
    out = replaceRegion(out, META_START, META_END, socialBlock({
      path,
      title: pageTitle(program.title),
      description,
    }), '<link rel="icon"');
    out = out.replace("<head>", `<head>\n${GENERATED_MARK}`);
    output.set(`programs/${program.slug}.html`, out);
  }

  /* The two crawler files, generated from the same list. */
  output.set("sitemap.xml", sitemap(programs));
  output.set("robots.txt",
    ["User-agent: *", "Allow: /", "", `Sitemap: ${SITE_URL}/sitemap.xml`, ""].join("\n"));

  /* Generated programme files whose programme is no longer published. */
  const stale = readdirSync(join(SITE, "programs"))
    .filter((f) => f.endsWith(".html") && f !== "index.html" && f !== "program.html")
    .filter((f) => readFileSync(join(SITE, "programs", f), "utf8").includes(GENERATED_MARK))
    .filter((f) => !output.has(`programs/${f}`))
    .map((f) => `programs/${f}`);

  return { output, stale, programs };
}

function sitemap(programs) {
  const urls = [
    { loc: "/", priority: "1.0" },
    { loc: "/programs/index.html", priority: "0.9" },
    ...programs.map((p) => ({ loc: `/programs/${p.slug}.html`, priority: "0.8" })),
    { loc: "/verify/index.html", priority: "0.3" },
    { loc: "/login.html", priority: "0.2" },
    { loc: "/register.html", priority: "0.2" },
  ];
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    ...urls.map(({ loc, priority }) =>
      `  <url><loc>${SITE_URL}${loc}</loc><priority>${priority}</priority></url>`),
    "</urlset>",
    "",
  ].join("\n");
}

/* --- Run ------------------------------------------------------------------ */

const { output, stale, programs } = await main();

/**
 * Everything below the work itself is about actually exiting.
 *
 * The Supabase client is built for a browser tab (assets/js/supabase.js sets
 * `autoRefreshToken: true`), so creating it schedules a repeating timer and
 * leaves a MessagePort open. In a tab that is the point. In a one-shot script
 * both are handles that keep the event loop alive after the work is done, and
 * the process simply never returns — which on Netlify is not a hung script but
 * a build that runs until it times out.
 *
 * stopAutoRefresh() deals with the timer. Nothing exposed deals with the port,
 * so the exit is explicit. It comes after the reporting below, so nothing is
 * cut off mid-write.
 */
const { sb } = await import(new URL("../site/assets/js/supabase.js", import.meta.url));
sb.auth.stopAutoRefresh();

if (CHECK) {
  const wrong = [];
  for (const [rel, next] of output) {
    let current = null;
    try { current = readFileSync(join(SITE, rel), "utf8"); } catch { /* missing */ }
    if (current !== next) wrong.push(current === null ? `${rel} (missing)` : rel);
  }
  for (const rel of stale) wrong.push(`${rel} (stale — programme no longer published)`);

  if (wrong.length) {
    console.error("Generated pages are out of date:\n  " + wrong.join("\n  "));
    console.error("\nRun: node build/prerender.mjs");
    process.exit(1);
  }
  console.log(`generated pages up to date (${output.size} files, ${programs.length} programmes)`);
} else {
  let changed = 0;
  for (const [rel, next] of output) {
    let current = null;
    try { current = readFileSync(join(SITE, rel), "utf8"); } catch { /* new file */ }
    if (current === next) continue;
    writeFileSync(join(SITE, rel), next);
    changed++;
  }
  for (const rel of stale) unlinkSync(join(SITE, rel));

  console.log(
    `prerendered ${programs.length} programme${programs.length === 1 ? "" : "s"}: ` +
    `${changed} file${changed === 1 ? "" : "s"} changed, ${output.size} written in total` +
    (stale.length ? `, ${stale.length} removed` : ""),
  );
}

// The reporting above is done, so it is safe to cut the process short — which,
// per the note beside stopAutoRefresh(), is the only way this script ends.
process.exit(process.exitCode ?? 0);
